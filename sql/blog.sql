CREATE DATABASE IF NOT EXISTS blog CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE blog;

DROP TABLE IF EXISTS commentaires_blog;
DROP TABLE IF EXISTS billets_blog;

CREATE TABLE billets_blog (
  ID INT NOT NULL AUTO_INCREMENT,
  titre VARCHAR(120) NOT NULL,
  contenu TEXT NOT NULL,
  annonce TINYTEXT NOT NULL,
  date_billet DATETIME NOT NULL,
  categorie VARCHAR(12) NOT NULL,
  PRIMARY KEY (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE commentaires_blog (
  ID_comment INT NOT NULL AUTO_INCREMENT,
  nom VARCHAR(50) NOT NULL,
  comment TEXT NOT NULL,
  date_comment TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ID INT NOT NULL,
  PRIMARY KEY (ID_comment),
  FOREIGN KEY (ID) REFERENCES billets_blog(ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
